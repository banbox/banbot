func (s *Store) Intent(ctx context.Context, id VirtualIntentID) (EligibleIntent, error) {
	var intent EligibleIntent
	err := s.commit(ctx, func(tx *storeTxn) error {
		var body string
		if err := tx.QueryRow(opReadIntentRuntime, s.accountID, string(id)).Scan(&body); err != nil {
			return err
		}
		if err := json.Unmarshal([]byte(body), &intent); err != nil {
			return err
		}
		if err := tx.QueryRow(opReadIntentFilled, s.accountID, string(id), s.accountID, string(id)).Scan(&intent.FilledSteps); err != nil {
			return err
		}
		if err := tx.QueryRow(opReadIntentReserved, s.accountID, string(id)).Scan(&intent.ReservedSteps); err != nil {
			return err
		}
		if intent.FilledSteps > intent.QuantitySteps {
			return errors.New("execution: late fills exceeded virtual intent; reconciliation required")
		}
		if intent.FilledSteps == intent.QuantitySteps {
			intent.State = Filled
		} else if intent.State != Canceled && intent.State != Expired {
			if intent.FilledSteps > 0 {
				intent.State = Partial
			} else if intent.ReservedSteps > 0 {
				intent.State = Reserved
			}
		}
		return nil
	})
	return intent, err
}

// EvaluateIntent checkpoints only trigger/expiry state. Fill and reservation
// highwaters remain derived from immutable allocation records.
func (s *Store) EvaluateIntent(ctx context.Context, id VirtualIntentID, observation ExecutionObservation, nowMS int64) (EligibleIntent, int64, error) {
	var intent EligibleIntent
	var available int64
	if observation.AtMS < 0 || observation.AtMS > nowMS || observation.ValidUntilMS <= nowMS {
		return intent, 0, errors.New("execution: invisible/expired intent observation")
	}
	err := s.commit(ctx, func(tx *storeTxn) error {
		var body string
		if err := tx.QueryRow(opReadIntentRuntime, s.accountID, string(id)).Scan(&body); err != nil {
			return err
		}
		if err := json.Unmarshal([]byte(body), &intent); err != nil {
			return err
		}
		var err error
		available, err = intent.Evaluate(observation.Price, nowMS, observation.Bar)
		if err != nil {
			return err
		}
		body, err = payload(intent)
		if err != nil {
			return err
		}
		if _, err := tx.Exec(opUpdateIntentRuntime, body, s.accountID, string(id)); err != nil {
			return err
		}
		var consumed int64
		if err := tx.QueryRow(opReadIntentConsumed, s.accountID, string(id), s.accountID, string(id)).Scan(&consumed); err != nil {
			return err
		}
		available = max(0, available-consumed)
		return nil
	})
	return intent, available, err
}

