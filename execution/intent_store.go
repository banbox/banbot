func (s *Store) StrategyCheckpoint(ctx context.Context, strategy StrategyID, name string) (json.RawMessage, error) {
	if !canonicalID(string(strategy)) || !canonicalID(name) {
		return nil, errors.New("execution: invalid strategy checkpoint identity")
	}
	var body string
	err := s.commit(ctx, func(tx *storeTxn) error {
		return tx.QueryRow(opReadStrategyCheckpoint, s.accountID, string(strategy), name).Scan(&body)
	})
	return json.RawMessage(body), err
}
func (s *Store) SaveStrategyCheckpoint(ctx context.Context, strategy StrategyID, name string, body json.RawMessage) error {
	if strategy == "account-risk" && name == "policy-v1" {
		return errors.New("execution: account policy requires immutable registration")
	}
	if !canonicalID(string(strategy)) || !canonicalID(name) || !json.Valid(body) {
		return errors.New("execution: invalid strategy checkpoint")
	}
	return s.commit(ctx, func(tx *storeTxn) error {
		_, err := tx.Exec(opPutStrategyCheckpoint, s.accountID, string(strategy), name, string(body))
		return err
	})
}
